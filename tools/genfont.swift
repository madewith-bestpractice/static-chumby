// Renders IBM Plex Sans (the app's typeface) into 8-bit alpha bitmaps for the
// Chumby client, which has no font rasterizer. Run on a Mac:
//   swift tools/genfont.swift > src/fonts.h      (from the repo root; `make fonts`)
// Each face: name, pixel size, weight (wght axis), width (wdth axis).
import CoreText
import CoreGraphics
import Foundation

let plex = "tools/fonts/IBMPlexSans-VariableFont_wdth,wght.ttf"   // SIL OFL 1.1
// Onest (SIL OFL 1.1): the station labels. staticradio.app uses General Sans, whose
// license (ITF FFL) forbids redistributing bitmap conversions, so this repo can't.
let onest = "tools/fonts/Onest[wght].ttf"
// stroke > 0 emboldens by also stroking the outline
let faces: [(name: String, px: CGFloat, wght: Double, wdth: Double, file: String, stroke: CGFloat)] = [
    ("font_clock", 17, 600, 100, plex, 0),        // clock
    ("font_small", 15, 450, 100, plex, 0),        // episode title
    ("font_show",  19, 600, 100, plex, 0),        // show (feed) name
    ("font_dial",  15, 650, 90, plex, 0),         // (legacy dial strip)
    ("font_tag",   48, 700, 85, plex, 0),         // big station tag
    ("font_label", 15, 500, 0, onest, 0),         // station labels down the right
    ("font_label_bold", 15, 700, 0, onest, 0),    // the selected station
]

func tag(_ s: String) -> Int { s.utf8.reduce(0) { ($0 << 8) | Int($1) } }


var out = "/* Generated by tools/genfont.swift. Glyph bitmaps rendered from IBM Plex Sans and Onest;\n * as converted fonts they remain under the SIL Open Font License 1.1 (LICENSES/). Do not edit. */\n"
out += "#pragma once\n#include \"font.h\"\n\n"

for f in faces {
    guard let descs = CTFontManagerCreateFontDescriptorsFromURL(URL(fileURLWithPath: f.file) as CFURL) as? [CTFontDescriptor],
          var d = descs.first else { fatalError("cannot load \(f.file)") }
    if f.wght > 0 {   // variable font axes
        d = CTFontDescriptorCreateCopyWithVariation(d, tag("wght") as CFNumber, CGFloat(f.wght))
        if f.wdth > 0 { d = CTFontDescriptorCreateCopyWithVariation(d, tag("wdth") as CFNumber, CGFloat(f.wdth)) }
    }
    let font = CTFontCreateWithFontDescriptor(d, f.px, nil)
    let ascent = Int(ceil(CTFontGetAscent(font)))
    let descent = Int(ceil(CTFontGetDescent(font)))
    var bitmap: [UInt8] = []
    var glyphLines: [String] = []
    for code in 32...126 {
        var ch = UniChar(code)
        var g = CGGlyph(0)
        CTFontGetGlyphsForCharacters(font, &ch, &g, 1)
        var adv = CGSize.zero
        CTFontGetAdvancesForGlyphs(font, .horizontal, &g, &adv, 1)
        var r = CGRect.zero
        CTFontGetBoundingRectsForGlyphs(font, .horizontal, &g, &r, 1)
        let x0 = Int(floor(r.minX)) - 1, x1 = Int(ceil(r.maxX)) + 1
        let y0 = Int(floor(r.minY)) - 1, y1 = Int(ceil(r.maxY)) + 1
        let w = max(0, x1 - x0), h = max(0, y1 - y0)
        let offset = bitmap.count
        if w > 0 && h > 0 && code != 32 {
            let ctx = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                                space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
            ctx.setFillColor(gray: 0, alpha: 1); ctx.fill(CGRect(x: 0, y: 0, width: w, height: h))
            ctx.setFillColor(gray: 1, alpha: 1)
            ctx.setAllowsFontSmoothing(false)
            if f.stroke > 0 {
                ctx.setTextDrawingMode(.fillStroke)
                ctx.setStrokeColor(gray: 1, alpha: 1)
                ctx.setLineWidth(f.stroke)
            }
            var pos = CGPoint(x: CGFloat(-x0), y: CGFloat(-y0))
            CTFontDrawGlyphs(font, &g, &pos, 1, ctx)
            let data = ctx.data!.assumingMemoryBound(to: UInt8.self)
            for row in 0..<h { for col in 0..<w { bitmap.append(data[row * w + col]) } }  // row 0 = top
        }
        // xoff: pen-relative left; yoff: top of bitmap relative to baseline (positive = above)
        let stored = (code == 32) ? (0, 0) : (w, h)
        glyphLines.append("  {\(stored.0), \(stored.1), \(x0), \(y1), \(Int(adv.width.rounded())), \(offset)},")
    }
    out += "static const uint8_t \(f.name)_bits[\(max(bitmap.count, 1))] = {"
    for (i, b) in bitmap.enumerated() { out += (i % 24 == 0 ? "\n  " : "") + "\(b)," }
    out += "\n};\n"
    out += "static const glyph_t \(f.name)_glyphs[95] = {\n" + glyphLines.joined(separator: "\n") + "\n};\n"
    out += "static const font_t \(f.name) = { \(Int(f.px)), \(ascent), \(descent), \(f.name)_glyphs, \(f.name)_bits };\n\n"
}
print(out)
