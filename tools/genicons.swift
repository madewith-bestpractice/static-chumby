// Reads the Static app's brand assets (mobile_app/, not in this repo); the
// generated header is checked in, so you only need this to change the artwork.
// Pre-renders the app's control icons as 8-bit alpha bitmaps for the Chumby:
// the 11 daily listener faces (mobile_app/assets/faces, Material Symbols PNGs)
// and the Material Icons the phone uses (heart filled/outline, faves list,
// plus info). Run on a Mac:  swift tools/genicons.swift > src/icons.h
import CoreText
import CoreGraphics
import Foundation
import ImageIO

let materialFont = "/opt/homebrew/share/flutter/bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf"
let facePx = 26, iconPx = 26
let faces = ["face", "face_2", "face_3", "face_4", "face_5", "face_6", "mood",
             "sentiment_calm", "sentiment_satisfied", "sentiment_very_satisfied", "sentiment_excited"]
// Flutter Icons codepoints (packages/flutter/lib/src/material/icons.dart)
let glyphs: [(String, UInt32)] = [("heart_fill", 0xf738), ("heart_line", 0xf737),
                                   ("faves_list", 0xe3de), ("info", 0xf815),
                                   ("volume", 0xf029a), ("volume_off", 0xf0299),
                                   ("close", 0xf647), ("qr", 0xf00cb)]

func alphaBitmap(_ w: Int, _ h: Int, draw: (CGContext) -> Void) -> [UInt8] {
    let ctx = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setFillColor(gray: 0, alpha: 1); ctx.fill(CGRect(x: 0, y: 0, width: w, height: h))
    ctx.interpolationQuality = .high
    draw(ctx)
    let d = ctx.data!.assumingMemoryBound(to: UInt8.self)
    return (0..<(w * h)).map { d[$0] }
}

var out = "/* Generated by tools/genicons.swift. Faces: mobile_app/assets/faces (Material Symbols);\n"
out += " * icons: Material Icons (Apache 2.0) from the Flutter SDK. Do not edit. */\n#pragma once\n#include \"ui.h\"\n\n"
out += ""

func emit(_ name: String, _ w: Int, _ h: Int, _ bits: [UInt8]) {
    out += "static const uint8_t \(name)_bits[\(w * h)] = {"
    for (i, b) in bits.enumerated() { out += (i % 26 == 0 ? "\n  " : "") + "\(b)," }
    out += "\n};\nstatic const icon_t \(name) = { \(w), \(h), \(name)_bits };\n\n"
}

for f in faces {
    let url = URL(fileURLWithPath: "mobile_app/assets/faces/\(f).png")
    guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
          let img = CGImageSourceCreateImageAtIndex(src, 0, nil) else { fatalError("face \(f)") }
    // the PNGs are dark glyphs on transparency: use their alpha as coverage
    let ctx = CGContext(data: nil, width: facePx, height: facePx, bitsPerComponent: 8, bytesPerRow: facePx * 4,
                        space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    ctx.interpolationQuality = .high
    ctx.draw(img, in: CGRect(x: 0, y: 0, width: facePx, height: facePx))
    let d = ctx.data!.assumingMemoryBound(to: UInt8.self)
    emit("icon_\(f)", facePx, facePx, (0..<(facePx * facePx)).map { d[$0 * 4 + 3] })
}
out += "static const icon_t *const icon_faces[\(faces.count)] = {" + faces.map { "&icon_\($0)" }.joined(separator: ", ") + "};\n\n"

guard let descs = CTFontManagerCreateFontDescriptorsFromURL(URL(fileURLWithPath: materialFont) as CFURL) as? [CTFontDescriptor],
      let fd = descs.first else { fatalError("material font") }
// (name, codepoint, px): most at iconPx; the resting volume glyph is sized to
// the clock beside it.
let sized: [(String, UInt32, Int)] = glyphs.map { ($0.0, $0.1, iconPx) } +
    [("volume_sm", 0xf029a, 18), ("volume_off_sm", 0xf0299, 18),
     ("minus_sm", 0xf00f1, 18), ("plus_sm", 0xf537, 18)]
for (name, cp, px) in sized {
    let font = CTFontCreateWithFontDescriptor(fd, CGFloat(px), nil)
    let iconPx = px
    var chars = Array(String(UnicodeScalar(cp)!).utf16)
    var g = [CGGlyph](repeating: 0, count: chars.count)
    CTFontGetGlyphsForCharacters(font, &chars, &g, chars.count)
    let bits = alphaBitmap(iconPx, iconPx) { ctx in
        ctx.setFillColor(gray: 1, alpha: 1)
        // Material icons sit in a 24-unit em box with the baseline at the bottom
        var pos = CGPoint(x: 0, y: 0)
        CTFontDrawGlyphs(font, &g, &pos, 1, ctx)
    }
    emit("icon_\(name)", iconPx, iconPx, bits)
}
print(out)
