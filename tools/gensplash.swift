// Reads the Static app's brand assets (mobile_app/, not in this repo); the
// generated header is checked in, so you only need this to change the artwork.
// The phone's launch screen for the Chumby: the Static logo
// (mobile_app/assets/brand/splash-logo.png) on the app's splash teal #62FFED
// (pubspec flutter_native_splash), rendered as 320x240 RGB565.
//   swift tools/gensplash.swift > src/splash.h
import CoreGraphics
import Foundation
import ImageIO

let W = 320, H = 240
guard let src = CGImageSourceCreateWithURL(URL(fileURLWithPath: "mobile_app/assets/brand/splash-logo.png") as CFURL, nil),
      let img = CGImageSourceCreateImageAtIndex(src, 0, nil) else { fatalError("logo") }
let ctx = CGContext(data: nil, width: W, height: H, bitsPerComponent: 8, bytesPerRow: W * 4,
                    space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
ctx.setFillColor(red: 0x62 / 255.0, green: 1.0, blue: 0xED / 255.0, alpha: 1)
ctx.fill(CGRect(x: 0, y: 0, width: W, height: H))
ctx.interpolationQuality = .high
// the logo art spans ~42% of the 2048 square; draw the square so the logo is ~250 px wide
let side = 600.0
ctx.draw(img, in: CGRect(x: (Double(W) - side) / 2, y: (Double(H) - side) / 2 - 6, width: side, height: side))
let d = ctx.data!.assumingMemoryBound(to: UInt8.self)
var out = "/* Generated by tools/gensplash.swift. Do not edit. */\n#pragma once\n#include <stdint.h>\n\nstatic const uint16_t splash_565[\(W * H)] = {"
for i in 0..<(W * H) {
    let r = UInt16(d[i * 4]), g = UInt16(d[i * 4 + 1]), b = UInt16(d[i * 4 + 2])
    let v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    out += (i % 16 == 0 ? "\n  " : "") + "0x" + String(v, radix: 16) + ","
}
out += "\n};\n"
print(out)
